function toReign(eraId: EraId, raw: RawReign): Reign {
  const life = raw.l ?? ''
  return {
    id: slugify(raw.n, raw.y),
    eraId,
    years: raw.y,
    name: raw.n,
    nick: raw.q,
    origin: raw.o,
    life,
    dynasty: raw.dynasty,
    personKey: raw.personKey ?? slugify(raw.n, 'person'),
    violentDeath: /х$/.test(life),
    approx: /~/.test(`${raw.y} ${life}`),
    added: Boolean(raw.add),
    posterNote: raw.posterNote,
  }
}

export const TIMELINE: TimelineItem[] = []
export const REIGNS: Reign[] = []

for (const block of RAW) {
  for (const item of block.items) {
    if ('div' in item) {
      TIMELINE.push({
        kind: 'dynasty',
        eraId: block.eraId,
        title: item.div,
        sub: item.sub,
        pill: item.pill,
      })
    } else {
      const reign = toReign(block.eraId, item)
      REIGNS.push(reign)
      TIMELINE.push({ kind: 'reign', eraId: block.eraId, reign })
    }
  }
}

const idCounts = new Map<string, number>()
for (const r of REIGNS) {
  const n = (idCounts.get(r.id) ?? 0) + 1
  idCounts.set(r.id, n)
  if (n > 1) r.id = `${r.id}-${n}`
}

export const DYNASTIES = [...new Set(REIGNS.map((r) => r.dynasty).filter(Boolean))]

export function eraById(id: EraId): Era {
  return ERAS.find((e) => e.id === id)!
}

export function reignById(id: string): Reign | undefined {
  return REIGNS.find((r) => r.id === id)
}

export function reignsByPerson(personKey: string): Reign[] {
  return REIGNS.filter((r) => r.personKey === personKey)
}

